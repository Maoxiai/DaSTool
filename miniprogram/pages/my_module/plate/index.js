Page({
  data: {
    plate: '',
    result: null,
    error: ''
  },

  onField(e) {
    this.setData({ plate: e.detail.value });
    this.compute();
  },

  compute() {
    this.setData({ result: null, error: '' });
    const plate = (this.data.plate || '').trim().toUpperCase();
    if (!plate) return;

    if (!/^[\u4e00-\u9fa5][A-Z]/.test(plate)) {
      this.setData({ error: '请输入正确车牌，如 粤B12345' });
      return;
    }

    const prov = plate[0];
    const cityLetter = plate[1];
    const provinceName = PROVINCE[prov];
    const cityName = CITY[prov] ? CITY[prov][cityLetter] : null;

    this.setData({
      result: {
        province: provinceName || '未知省份',
        city: cityName || (provinceName ? '城市代码 ' + cityLetter : '未识别')
      }
    });
  }
});